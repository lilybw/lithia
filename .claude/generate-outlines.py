"""Writes Rust-like outlines of the lithia and lithia-macro crates to .claude/outlined/, mirroring their
layout: crates/lithia/src/graph/sched.rs becomes .claude/outlined/lithia/src/graph/outlined.sched.rs.

  generate-outlines.py                         rebuild stale and missing outlines, drop orphans, write INDEX.md
  generate-outlines.py --all                   rebuild every outline
  generate-outlines.py --status [--markdown]   which outlines match their sources; writes nothing
  generate-outlines.py --check                 like --status, but exits 1 unless all are current

Each outline keeps signatures, doc comments and struct fields, leaves bodies out, and notes each item's
source line as `// L<n>`. Its header records a hash of its source and of the generator, which is how a
stale outline is found without reading any code. `.ignore` keeps them out of repository-wide searches.
"""

from __future__ import annotations

import hashlib
import io
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "tools"))
from outline import ROOT, outline_rust  # noqa: E402

CRATES: dict[str, str] = {"lithia": "crates/lithia", "macro": "crates/macro"}
OUT: Path = ROOT / ".claude/outlined"
INDEX: Path = OUT / "INDEX.md"
TOOLS: list[Path] = [Path(__file__).resolve(), ROOT / ".claude/tools/outline.py"]
# Line ends normalised, so a CRLF checkout of the tools stamps outlines as CI does.
GENERATOR: str = hashlib.sha256(b"".join(p.read_bytes().replace(b"\r\n", b"\n") for p in TOOLS)).hexdigest()[:12]
STAMP: re.Pattern[str] = re.compile(r"^// source ([0-9a-f]{16}), generator ([0-9a-f]{12})$", re.M)
INDEX_STAMP: re.Pattern[str] = re.compile(r"^<!-- sources ([0-9a-f]{16}), generator ([0-9a-f]{12}) -->$", re.M)
States = dict[str, str]


def sources() -> list[Path]:
    """The crates' Rust files that git tracks or would track."""
    listed: str = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "--", *CRATES.values()],
        cwd=ROOT, capture_output=True, encoding="utf-8", errors="replace", check=True,
    ).stdout
    return sorted(Path(p) for p in set(listed.splitlines()) if p.endswith(".rs") and (ROOT / p).is_file())


def outlined(source: Path) -> Path:
    """Where the outline of `source` lives."""
    for name, crate in CRATES.items():
        if source.is_relative_to(crate):
            relative: Path = source.relative_to(crate)
            return OUT / name / relative.parent / f"outlined.{relative.name}"
    raise ValueError(f"{source} is in neither crate")


def source_hash(source: Path) -> str:
    """A hash of the source with LF line ends, so a CRLF checkout hashes as CI's LF one does."""
    return hashlib.sha256((ROOT / source).read_bytes().replace(b"\r\n", b"\n")).hexdigest()[:16]


def render(source: Path) -> str:
    text: str = (ROOT / source).read_text(encoding="utf-8")
    lines: int = text.count("\n")
    header: list[str] = [
        "// SPDX-FileCopyrightText: 2026 lithia Authors",
        "// SPDX-License-Identifier: MPL-2.0",
        f"// Outline of {source.as_posix()} ({lines} lines): signatures and docs, no bodies; `// L<n>` is the",
        "// source line. Generated by .claude/generate-outlines.py: edit the source, not this file.",
        f"// source {source_hash(source)}, generator {GENERATOR}",
        "",
    ]
    return "\n".join(header + outline_rust(text, False, stub=True)) + "\n"


def state(source: Path) -> str:
    target: Path = outlined(source)
    if not target.is_file():
        return "missing"
    stamp: re.Match[str] | None = STAMP.search(target.read_text(encoding="utf-8", errors="replace"))
    if stamp is None or stamp.group(1) != source_hash(source):
        return "stale"
    return "current" if stamp.group(2) == GENERATOR else "stale (generator changed)"


def orphans(files: list[Path]) -> list[Path]:
    """Outlines whose source is gone."""
    wanted: set[Path] = {outlined(f) for f in files}
    return sorted(p for p in OUT.rglob("outlined.*.rs") if p not in wanted) if OUT.is_dir() else []


def sources_hash(files: list[Path]) -> str:
    digest = hashlib.sha256()
    for f in files:
        digest.update(f.as_posix().encode() + b"\0" + source_hash(f).encode())
    return digest.hexdigest()[:16]


def index_state(files: list[Path]) -> str:
    if not INDEX.is_file():
        return "missing"
    stamp: re.Match[str] | None = INDEX_STAMP.search(INDEX.read_text(encoding="utf-8"))
    if stamp is None or stamp.group(1) != sources_hash(files):
        return "stale"
    return "current" if stamp.group(2) == GENERATOR else "stale (generator changed)"


def first_doc(source: Path) -> str:
    """The first line of a file's own module doc."""
    found: re.Match[str] | None = re.search(r"^//!\s?(.*)$", (ROOT / source).read_text(encoding="utf-8"), re.M)
    return found.group(1).replace("|", "\\|") if found else ""


def write_index(files: list[Path]) -> None:
    rows: list[str] = []
    for f in files:
        doc: str = first_doc(f)
        lines: int = (ROOT / f).read_bytes().count(b"\n")
        rows.append(f"| [`{f.as_posix()}`]({outlined(f).relative_to(OUT).as_posix()}) | {lines} | {doc} |")
    write(INDEX, "\n".join([
        "<!-- SPDX-FileCopyrightText: 2026 lithia Authors -->",
        "<!-- SPDX-License-Identifier: MPL-2.0 -->",
        f"<!-- sources {sources_hash(files)}, generator {GENERATOR} -->",
        "",
        "# Outlines of lithia's crates",
        "",
        "Generated by `.claude/generate-outlines.py`; each file's header says whether it still matches its",
        "source. The first line of each file's module doc says what it is for.",
        "",
        "| Source | Lines | What it is |",
        "| --- | ---: | --- |",
        *rows,
    ]) + "\n")


def write(path: Path, text: str) -> None:
    """Writes UTF-8 with LF line ends on every platform, as the repository stores text."""
    path.write_text(text, encoding="utf-8", newline="\n")


def report(files: list[Path], markdown: bool) -> States:
    states: States = {f.as_posix(): state(f) for f in files}
    states[".claude/outlined/INDEX.md"] = index_state(files)
    for gone in orphans(files):
        states[gone.relative_to(ROOT).as_posix()] = "orphaned"
    counts: dict[str, int] = {}
    for s in states.values():
        key: str = s.split(" ")[0]
        counts[key] = counts.get(key, 0) + 1
    line: str = ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
    if not OUT.is_dir():
        message: str = "No outlines are committed; `python3 .claude/generate-outlines.py` writes them."
        print(f"### Outlines\n\n{message}" if markdown else message)
        return states
    off: list[tuple[str, str]] = [(p, s) for p, s in sorted(states.items()) if s != "current"]
    if markdown:
        print(f"### Outlines: {line}\n")
        if off:
            print("| Source | State |\n| --- | --- |")
            print("\n".join(f"| `{p}` | {s} |" for p, s in off))
            print("\n`python3 .claude/generate-outlines.py` brings them up to date.")
        print("\n<details><summary>Every outline</summary>\n\n| Source | State |\n| --- | --- |")
        print("\n".join(f"| `{p}` | {s} |" for p, s in sorted(states.items())))
        print("\n</details>")
    else:
        print(f"outlines: {line}")
        for p, s in off:
            print(f"  {s:<26} {p}")
    return states


def generate(files: list[Path], everything: bool) -> None:
    rebuilt: int = 0
    for f in files:
        if everything or state(f) != "current":
            target: Path = outlined(f)
            target.parent.mkdir(parents=True, exist_ok=True)
            write(target, render(f))
            rebuilt += 1
    removed: list[Path] = orphans(files)
    for gone in removed:
        gone.unlink()
    for folder in sorted({p.parent for p in removed}, key=lambda d: len(d.parts), reverse=True):
        while folder != OUT and folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
            folder = folder.parent
    if everything or index_state(files) != "current":
        write_index(files)
    print(f"outlines: {rebuilt} rebuilt, {len(removed)} removed, {len(files) - rebuilt} already current")


def main(argv: list[str]) -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles default to a code page
    files: list[Path] = sources()
    if "--status" in argv or "--check" in argv:
        states: States = report(files, "--markdown" in argv)
        return 1 if "--check" in argv and any(s != "current" for s in states.values()) else 0
    if argv and argv != ["--all"]:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.mkdir(parents=True, exist_ok=True)
    generate(files, argv == ["--all"])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
